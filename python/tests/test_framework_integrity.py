"""Integrity of the framework bundle generated from the Go loader (internal/compliance/gen)."""
from __future__ import annotations

import json
from importlib import resources
from pathlib import Path

import pytest
import yaml

from nimbus.compliance import build_report, frameworks, load_frameworks
from nimbus.models import Finding

from .conftest import F

REPO = Path(__file__).resolve().parents[2]


def _raw_text() -> str:
    return resources.files("nimbus").joinpath("frameworks/frameworks.yaml").read_text(encoding="utf-8")


def _no_dupes(pairs):
    keys = [k for k, _ in pairs]
    dupes = sorted({k for k in keys if keys.count(k) > 1})
    if dupes:
        raise AssertionError(f"duplicate keys in bundle: {dupes[:10]}")
    return dict(pairs)


@pytest.fixture(scope="module")
def bundle() -> dict:
    return json.loads(_raw_text(), object_pairs_hook=_no_dupes)


def test_bundle_is_generated_and_parses_as_yaml_too(bundle):
    assert bundle["_generated"].startswith("GENERATED by internal/compliance/gen")
    loader = getattr(yaml, "CSafeLoader", None)
    if loader is not None:  # the pure-Python loader is too slow for a 2 MB file in a unit test
        assert yaml.load(_raw_text(), Loader=loader) == bundle
    assert len(bundle["frameworks"]) >= 123  # 11 hand-written + 112 imported from Prowler


def test_counts_and_coverage_match_declared(bundle):
    fws = load_frameworks()
    assert set(fws) == set(bundle["frameworks"])
    listing = {f["key"]: f for f in frameworks()}
    for key, raw in bundle["frameworks"].items():
        n = raw["control_count"]
        assert len(fws[key].controls) == n == len(raw["controls"]), key
        cov = raw["coverage"]
        assert cov["native"] + cov["prowler_ingest"] + cov["manual"] == n, key
        assert fws[key].coverage == cov and listing[key]["coverage"] == cov and listing[key]["controls"] == n


def test_imported_frameworks_carry_provenance(bundle):
    imported = {k: v for k, v in bundle["frameworks"].items() if "provenance" in v}
    assert len(imported) == 112
    for key, raw in imported.items():
        p = raw["provenance"]
        assert p["license"] == "Apache-2.0" and "Prowler" in p["attribution"] and p["source"].startswith("prowler@"), key
    fw = load_frameworks()["cis_3.0_aws"]
    assert fw.provenance["upstream_url"].startswith("https://github.com/prowler-cloud/prowler/blob/")


def _catalog_titles() -> set[str]:
    path = REPO / "internal" / "catalog" / "catalog.yaml"
    if not path.exists():
        pytest.skip("Go catalog not available outside the repository")
    return {str(e.get("title", "")) for e in (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).values()}


def test_cis_imported_controls_hold_no_upstream_text(bundle):
    titles = _catalog_titles() | {""}
    cis = {k: v for k, v in bundle["frameworks"].items() if "provenance" in v and k.startswith("cis_")}
    assert len(cis) >= 30
    for key, raw in cis.items():
        assert raw["provenance"]["reference_url"].startswith("https://www.cisecurity.org/"), key
        for cid, ctl in raw["controls"].items():
            assert set(ctl) <= {"title", "checks"}, (key, cid)
            assert ctl["title"] in titles, (key, cid, ctl["title"])


def test_imported_framework_maps_findings_by_check():
    fs = [
        F(check_id="iam_user_mfa_enabled_console_access", canonical_id="IAM_USER_NO_MFA", resource={"id": "u/alice", "name": "alice"}),
        F(check_id="account_maintain_current_contact_details", status="PASS", resource={"id": "acct"}),
    ]
    assert fs[1].canonical_id == "PROWLER:account_maintain_current_contact_details"
    rep = build_report("cis_3.0_aws", fs)
    c = {x.id: x for x in rep.controls}
    assert c["1.10"].status == "FAIL" and c["1.10"].evidence[0].mapped_by == "canonical_id"
    assert c["1.1"].status == "PASS"
    assert rep.assessed == rep.passing + rep.failing >= 2
    assert sum(rep.coverage.values()) == rep.total_controls == 62
    assert rep.coverage["native"] > 0 and rep.coverage["prowler_ingest"] > 0


def test_hand_written_report_has_denominator():
    rep = build_report("cis_aws", [F(check_id="x", canonical_id="IAM_USER_NO_MFA", compliance={"cis_aws": ["1.10"]}, resource={"id": "r"})])
    assert rep.assessed == 1 and rep.coverage["prowler_ingest"] == 0
    assert sum(rep.coverage.values()) == rep.total_controls
    assert isinstance(rep.framework, object) and Finding
