package compliance

import (
	"bytes"
	"encoding/json"
	"sort"
)

// BundlePath is where the generated Python bundle lives, relative to the repository root.
const BundlePath = "python/nimbus/frameworks/frameworks.yaml"

const bundleNote = "GENERATED by internal/compliance/gen (go generate ./internal/compliance/) from internal/compliance/frameworks.yaml, extra.yaml and frameworks/*.yaml (weakness_mappings come from extra.yaml, the single source). Do not edit. The file is JSON, which is also valid YAML."

// BundleJSON renders every framework Go loads (hand-written, extra.yaml, the ISO 27001:2022
// controls added in code, and the imported Prowler frameworks with their checks, coverage and
// provenance) as the Python engine's frameworks.yaml, together with Go's weakness -> control
// mappings (extra.yaml), so Python never keeps its own copy. One control per line keeps diffs readable.
func BundleJSON() ([]byte, error) {
	fws := Frameworks()
	weakness := WeaknessMappings()
	var b bytes.Buffer
	str := func(v any) {
		var buf bytes.Buffer
		enc := json.NewEncoder(&buf)
		enc.SetEscapeHTML(false)
		_ = enc.Encode(v)
		b.Write(bytes.TrimRight(buf.Bytes(), "\n"))
	}
	b.WriteString("{\n  \"_generated\": ")
	str(bundleNote)
	b.WriteString(",\n  \"frameworks\": {\n")
	keys := make([]string, 0, len(fws))
	for k := range fws {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for i, k := range keys {
		fw := fws[k]
		cov, _ := Coverage(k)
		b.WriteString("    ")
		str(k)
		b.WriteString(": {\n      \"name\": ")
		str(fw.Name)
		b.WriteString(",\n      \"version\": ")
		str(fw.Version)
		b.WriteString(",\n      \"control_count\": ")
		str(len(fw.Controls))
		b.WriteString(",\n      \"coverage\": ")
		str(cov)
		if fw.Provenance != nil {
			b.WriteString(",\n      \"provenance\": ")
			str(fw.Provenance)
		}
		b.WriteString(",\n      \"controls\": {")
		ids := make([]string, 0, len(fw.Controls))
		for id := range fw.Controls {
			ids = append(ids, id)
		}
		sort.Strings(ids)
		sort.SliceStable(ids, func(i, j int) bool { return controlLess(ids[i], ids[j]) })
		for j, id := range ids {
			if j > 0 {
				b.WriteString(",")
			}
			b.WriteString("\n        ")
			str(id)
			b.WriteString(": ")
			if fw.Provenance == nil {
				str(fw.Controls[id])
				continue
			}
			ctl := struct {
				Title  string   `json:"title"`
				Checks []string `json:"checks,omitempty"`
			}{fw.Controls[id], fw.Checks[id]}
			str(ctl)
		}
		b.WriteString("\n      }\n    }")
		if i < len(keys)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString("  },\n  \"weakness_mappings\": {")
	ws := make([]string, 0, len(weakness))
	for w := range weakness {
		ws = append(ws, w)
	}
	sort.Strings(ws)
	for i, w := range ws {
		if i > 0 {
			b.WriteString(",")
		}
		b.WriteString("\n    ")
		str(w)
		b.WriteString(": ")
		str(weakness[w])
	}
	b.WriteString("\n  }\n}\n")
	return b.Bytes(), nil
}
