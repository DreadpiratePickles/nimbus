// Package gitops turns patches into branches, commits and pull requests (GitHub / GitLab),
// with the explanation, risk, rollback and verification that a best-in-class fix PR carries.
package gitops

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/DreadpiratePickles/nimbus/internal/iac"
	"github.com/DreadpiratePickles/nimbus/internal/model"
)

type PROptions struct {
	RepoDir    string
	Branch     string // default cloud-posture/fix-<canonical>-<short id>
	BaseBranch string // default: current branch
	Title      string
	Labels     []string
	Draft      bool
	DryRun     bool
	Remote     string // default origin
	Token      string // GITHUB_TOKEN / GITLAB_TOKEN
	Host       string // github | gitlab (auto from remote URL)
	Author     string // "cloud-posture <bot@cloud-posture.dev>"
}

type PRResult struct {
	Branch   string `json:"branch"`
	Commit   string `json:"commit,omitempty"`
	URL      string `json:"url,omitempty"`
	Body     string `json:"body"`
	DryRun   bool   `json:"dry_run"`
	Files    []string `json:"files"`
}

func git(dir string, args ...string) (string, error) {
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	var out, errb bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errb
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("git %s: %s", strings.Join(args, " "), strings.TrimSpace(errb.String()))
	}
	return strings.TrimSpace(out.String()), nil
}

// RemoteInfo parses owner/repo and host from the git remote.
func RemoteInfo(dir, remote string) (host, ownerRepo string, err error) {
	url, err := git(dir, "remote", "get-url", remote)
	if err != nil {
		return "", "", err
	}
	u := strings.TrimSuffix(url, ".git")
	switch {
	case strings.Contains(u, "github.com"):
		host = "github"
	case strings.Contains(u, "gitlab"):
		host = "gitlab"
	}
	u = strings.TrimPrefix(u, "git@")
	u = strings.TrimPrefix(u, "https://")
	u = strings.TrimPrefix(u, "ssh://git@")
	if i := strings.IndexAny(u, ":/"); i >= 0 {
		ownerRepo = strings.Trim(u[i+1:], "/")
	}
	return host, ownerRepo, nil
}

// OpenFixPR applies patches on a new branch, commits, pushes and opens a PR.
func OpenFixPR(ctx context.Context, patches []iac.Patch, findings []model.Finding, paths []model.AttackPath, opts PROptions) (*PRResult, error) {
	if len(patches) == 0 {
		return nil, fmt.Errorf("no patches to apply")
	}
	if opts.RepoDir == "" {
		opts.RepoDir = "."
	}
	if opts.Remote == "" {
		opts.Remote = "origin"
	}
	for _, p := range patches {
		if p.WidensAccess {
			return nil, fmt.Errorf("guardrail: patch for %s would widen access; refusing to open a PR", p.Address)
		}
	}
	root, err := git(opts.RepoDir, "rev-parse", "--show-toplevel")
	if err != nil {
		return nil, err
	}
	base := opts.BaseBranch
	if base == "" {
		base, _ = git(root, "rev-parse", "--abbrev-ref", "HEAD")
	}
	branch := opts.Branch
	if branch == "" {
		branch = fmt.Sprintf("cloud-posture/fix-%s-%s", strings.ToLower(patches[0].CanonicalID), time.Now().UTC().Format("20060102-1504"))
	}
	body := PRBody(patches, findings, paths)
	res := &PRResult{Branch: branch, Body: body, DryRun: opts.DryRun}
	for _, p := range patches {
		res.Files = append(res.Files, p.File)
	}
	if opts.DryRun {
		return res, nil
	}
	if dirty, _ := git(root, "status", "--porcelain"); dirty != "" {
		return nil, fmt.Errorf("working tree has uncommitted changes; commit or stash first")
	}
	if _, err := git(root, "checkout", "-b", branch); err != nil {
		return nil, err
	}
	for _, p := range patches {
		full := p.File
		if !filepath.IsAbs(full) {
			full = filepath.Join(root, p.File)
		}
		if err := os.WriteFile(full, []byte(p.After), 0o644); err != nil {
			return nil, err
		}
		if _, err := git(root, "add", p.File); err != nil {
			return nil, err
		}
	}
	title := opts.Title
	if title == "" {
		title = fmt.Sprintf("fix(security): %s", summaryTitle(patches))
	}
	args := []string{"commit", "-m", title, "-m", "Generated by cloud-posture fix --auto-pr"}
	if opts.Author != "" {
		args = append(args, "--author", opts.Author)
	}
	if _, err := git(root, args...); err != nil {
		return nil, err
	}
	res.Commit, _ = git(root, "rev-parse", "--short", "HEAD")
	if _, err := git(root, "push", "-u", opts.Remote, branch); err != nil {
		return nil, err
	}
	host, ownerRepo, err := RemoteInfo(root, opts.Remote)
	if err != nil {
		return res, err
	}
	if opts.Host != "" {
		host = opts.Host
	}
	switch host {
	case "github":
		url, err := createGitHubPR(ctx, ownerRepo, opts.Token, title, body, branch, base, opts.Labels, opts.Draft)
		res.URL = url
		return res, err
	case "gitlab":
		url, err := createGitLabMR(ctx, ownerRepo, opts.Token, title, body, branch, base, opts.Labels)
		res.URL = url
		return res, err
	}
	return res, fmt.Errorf("pushed %s; open the pull request manually (unknown host)", branch)
}

func summaryTitle(ps []iac.Patch) string {
	seen := map[string]bool{}
	var ids []string
	for _, p := range ps {
		if !seen[p.CanonicalID] {
			seen[p.CanonicalID] = true
			ids = append(ids, strings.ToLower(strings.ReplaceAll(p.CanonicalID, "_", " ")))
		}
	}
	if len(ids) > 3 {
		return fmt.Sprintf("%s and %d more", strings.Join(ids[:3], ", "), len(ids)-3)
	}
	return strings.Join(ids, ", ")
}

// PRBody writes the explanation a reviewer needs: what changed, why, the risk, how it was validated,
// how to roll back, and the attack paths the change closes.
func PRBody(patches []iac.Patch, findings []model.Finding, paths []model.AttackPath) string {
	var b strings.Builder
	b.WriteString("## 🔐 Security fix generated by cloud-posture\n\n")
	b.WriteString("| Finding | Severity | File | Confidence |\n|---|---|---|---|\n")
	byAddr := map[string]model.Finding{}
	for _, f := range findings {
		byAddr[f.Resource.ID] = f
	}
	for _, p := range patches {
		sev := "-"
		if f, ok := byAddr[p.Address]; ok {
			sev = string(f.Severity)
		}
		fmt.Fprintf(&b, "| `%s` on `%s` | %s | `%s` | %.0f%% |\n", p.CanonicalID, p.Address, sev, p.File, p.Confidence*100)
	}
	b.WriteString("\n### What changed and why\n")
	for _, p := range patches {
		fmt.Fprintf(&b, "- **%s** (`%s`): %s\n", p.CanonicalID, p.Address, p.Explanation)
	}
	if len(paths) > 0 {
		b.WriteString("\n### Attack paths this closes\n")
		for i, ap := range paths {
			if i >= 5 {
				break
			}
			fmt.Fprintf(&b, "- %s → **%s** (score %.1f)\n", ap.Name, ap.Impact, ap.Score)
		}
	}
	b.WriteString("\n### Validation\n- Re-scanned the patched files with the cloud-posture native IaC rules: the fixed findings no longer fail.\n- Guardrail: the patch introduces no new world-open CIDR, public ACL, wildcard policy or public endpoint.\n")
	b.WriteString("\n### Risk & rollback\n- Changes are additive/narrowing only (`terraform plan` shows updates in place unless noted in the explanation).\n- Roll back with `git revert` of this commit; no state migration is required.\n")
	b.WriteString("\n<details><summary>Diff</summary>\n\n")
	for _, p := range patches {
		fmt.Fprintf(&b, "```diff\n%s\n```\n", p.Diff)
	}
	b.WriteString("\n</details>\n\n🤖 Generated with [cloud-posture](https://github.com/DreadpiratePickles/nimbus)\n")
	return b.String()
}

// SuggestionComment renders a GitHub "commit suggestion" block for a single-hunk patch so reviewers can apply it in one click.
func SuggestionComment(p iac.Patch, startLine, endLine int) string {
	lines := strings.Split(p.After, "\n")
	if startLine < 1 || endLine > len(lines) || startLine > endLine {
		return ""
	}
	return fmt.Sprintf("**%s** — %s\n\n```suggestion\n%s\n```", p.CanonicalID, p.Explanation, strings.Join(lines[startLine-1:endLine], "\n"))
}

func createGitHubPR(ctx context.Context, ownerRepo, token, title, body, head, base string, labels []string, draft bool) (string, error) {
	if token == "" {
		token = os.Getenv("GITHUB_TOKEN")
	}
	if token == "" {
		return "", fmt.Errorf("GITHUB_TOKEN required to open the pull request (branch pushed: %s)", head)
	}
	payload, _ := json.Marshal(map[string]any{"title": title, "body": body, "head": head, "base": base, "draft": draft})
	req, _ := http.NewRequestWithContext(ctx, http.MethodPost, "https://api.github.com/repos/"+ownerRepo+"/pulls", bytes.NewReader(payload))
	req.Header.Set("Authorization", "Bearer "+token)
	req.Header.Set("Accept", "application/vnd.github+json")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	data, _ := io.ReadAll(resp.Body)
	if resp.StatusCode >= 300 {
		return "", fmt.Errorf("github pulls API %d: %s", resp.StatusCode, truncate(string(data), 300))
	}
	var pr struct {
		HTMLURL string `json:"html_url"`
		Number  int    `json:"number"`
	}
	json.Unmarshal(data, &pr)
	if len(labels) > 0 {
		lp, _ := json.Marshal(map[string]any{"labels": labels})
		lreq, _ := http.NewRequestWithContext(ctx, http.MethodPost, fmt.Sprintf("https://api.github.com/repos/%s/issues/%d/labels", ownerRepo, pr.Number), bytes.NewReader(lp))
		lreq.Header.Set("Authorization", "Bearer "+token)
		lreq.Header.Set("Accept", "application/vnd.github+json")
		if r, err := http.DefaultClient.Do(lreq); err == nil {
			r.Body.Close()
		}
	}
	return pr.HTMLURL, nil
}

func createGitLabMR(ctx context.Context, project, token, title, body, source, target string, labels []string) (string, error) {
	if token == "" {
		token = os.Getenv("GITLAB_TOKEN")
	}
	if token == "" {
		return "", fmt.Errorf("GITLAB_TOKEN required (branch pushed: %s)", source)
	}
	payload, _ := json.Marshal(map[string]any{"title": title, "description": body, "source_branch": source, "target_branch": target, "labels": strings.Join(labels, ","), "remove_source_branch": true})
	req, _ := http.NewRequestWithContext(ctx, http.MethodPost, "https://gitlab.com/api/v4/projects/"+strings.ReplaceAll(project, "/", "%2F")+"/merge_requests", bytes.NewReader(payload))
	req.Header.Set("PRIVATE-TOKEN", token)
	req.Header.Set("Content-Type", "application/json")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	data, _ := io.ReadAll(resp.Body)
	if resp.StatusCode >= 300 {
		return "", fmt.Errorf("gitlab MR API %d: %s", resp.StatusCode, truncate(string(data), 300))
	}
	var mr struct {
		WebURL string `json:"web_url"`
	}
	json.Unmarshal(data, &mr)
	return mr.WebURL, nil
}

// PostPRComment posts (or updates) a sticky comment on a GitHub PR, used by the GitHub Action.
func PostPRComment(ctx context.Context, ownerRepo string, prNumber int, token, body string) error {
	if token == "" {
		token = os.Getenv("GITHUB_TOKEN")
	}
	marker := "<!-- cloud-posture-sticky -->"
	body = marker + "\n" + body
	hdr := func(r *http.Request) {
		r.Header.Set("Authorization", "Bearer "+token)
		r.Header.Set("Accept", "application/vnd.github+json")
	}
	// find existing
	lreq, _ := http.NewRequestWithContext(ctx, http.MethodGet, fmt.Sprintf("https://api.github.com/repos/%s/issues/%d/comments?per_page=100", ownerRepo, prNumber), nil)
	hdr(lreq)
	if resp, err := http.DefaultClient.Do(lreq); err == nil {
		var comments []struct {
			ID   int64  `json:"id"`
			Body string `json:"body"`
		}
		json.NewDecoder(resp.Body).Decode(&comments)
		resp.Body.Close()
		for _, c := range comments {
			if strings.Contains(c.Body, marker) {
				p, _ := json.Marshal(map[string]string{"body": body})
				ureq, _ := http.NewRequestWithContext(ctx, http.MethodPatch, fmt.Sprintf("https://api.github.com/repos/%s/issues/comments/%d", ownerRepo, c.ID), bytes.NewReader(p))
				hdr(ureq)
				r, err := http.DefaultClient.Do(ureq)
				if err == nil {
					r.Body.Close()
				}
				return err
			}
		}
	}
	p, _ := json.Marshal(map[string]string{"body": body})
	req, _ := http.NewRequestWithContext(ctx, http.MethodPost, fmt.Sprintf("https://api.github.com/repos/%s/issues/%d/comments", ownerRepo, prNumber), bytes.NewReader(p))
	hdr(req)
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return err
	}
	resp.Body.Close()
	if resp.StatusCode >= 300 {
		return fmt.Errorf("comment API %d", resp.StatusCode)
	}
	return nil
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n]
}
