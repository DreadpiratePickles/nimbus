// AttrDoc returns the documented type and meaning of a contract key.
func AttrDoc(key string) (typ, meaning string) { d := attrDocs[key]; return d[0], d[1] }

func yes(b bool) string {
	if b {
		return "yes"
	}
	return ""
}

// SchemaMarkdown renders docs/graph-schema.md from the registry, the edge kinds and the edge
// attribute contract. TestGraphSchemaDocCurrent fails when the committed file differs.
func SchemaMarkdown() string {
	var b strings.Builder
	b.WriteString("<!-- Code generated by `go generate ./internal/graph` (internal/graph/gen); DO NOT EDIT. -->\n\n")
	b.WriteString("# nimbus graph schema\n\n")
	b.WriteString("Generated from `internal/graph/registry.go`, `internal/graph/schema.go` and `internal/model/edge_attrs.go`. ")
	b.WriteString("`TestGraphSchemaDocCurrent` fails when this file is stale; `TestRegistryCoversCollectorTypes` fails when a collector or the lab estate emits a type that is not listed here.\n\n")
	reg := Registry()
	aliases := 0
	for _, s := range reg {
		aliases += len(s.Aliases)
	}
	fmt.Fprintf(&b, "## Node types (%d types, %d aliases)\n\n", len(reg), aliases)
	b.WriteString("A node whose type is not registered keeps the legacy substring class, is marked `guessed: true`, and its type is listed by `graph.UnregisteredTypes()`. ")
	b.WriteString("Aliases (Terraform, CloudFormation, ASFF, Kubernetes kind, Azure/GCP resource type) resolve case-insensitively to the canonical type; node `type` strings are not rewritten. ")
	b.WriteString("`crown` (crown-jewel default) and `admin` (admin-capable) are typed facts not yet read by scoring.\n\n")
	b.WriteString("| type | class | provider | display | identity | data store | admin | crown | id format | aliases |\n|---|---|---|---|---|---|---|---|---|---|\n")
	for _, s := range reg {
		al := make([]string, len(s.Aliases))
		for i, a := range s.Aliases {
			al[i] = "`" + a + "`"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s | %s | %s | `%s` | %s |\n", s.Type, s.Class, s.Provider, s.Display,
			yes(s.IsIdentity), yes(s.IsDataStore), yes(s.IsAdminCapable), yes(s.Crown), strings.ReplaceAll(s.IDFormat, "|", `\|`), strings.Join(al, ", "))
	}
	b.WriteString("\n## Classes\n\n")
	counts := map[string]int{}
	for _, s := range reg {
		counts[s.Class]++
	}
	b.WriteString("| class | types |\n|---|---|\n")
	for _, c := range []string{ClassInternet, ClassAccount, ClassIdentity, ClassCompute, ClassCluster, ClassNetwork, ClassDataStore, ClassImage, ClassSaaS} {
		fmt.Fprintf(&b, "| %s | %d |\n", c, counts[c])
	}
	b.WriteString("\n## Classes kept from the legacy heuristic (review)\n\n")
	b.WriteString("These types keep the class the substring heuristic gave them so analysis results do not move; reclassify only with a groundtruth and noise-estate re-baseline.\n\n| type | class | why review |\n|---|---|---|\n")
	for _, s := range reg {
		if s.Review != "" {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", s.Type, s.Class, s.Review)
		}
	}
	b.WriteString("\n## Edge kinds\n\n| kind | from | to | meaning |\n|---|---|---|---|\n")
	for _, k := range EdgeKinds {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", k.Kind, k.From, k.To, k.Meaning)
	}
	b.WriteString("\n## Edge attribute contract\n\n")
	b.WriteString("`graph.Edge.Attr` is a flat JSON object (stored verbatim in `graph_edges.attr`). The keys below are typed by `model.EdgeAttrs` ")
	b.WriteString("(`PermissionAttr`, `Exposure`, `Confidence`) and read/written with `Edge.Permission/SetPermission`, `Exposure/SetExposure`, ")
	b.WriteString("`Confidence/SetConfidence`, `Because/SetBecause`. Other keys (`via`, `ports`, `hint`, `finding_id`, ...) are collector detail and are preserved.\n\n")
	b.WriteString("| key | type | meaning |\n|---|---|---|\n")
	for _, k := range model.EdgeAttrKeys {
		t, m := AttrDoc(k)
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", k, t, m)
	}
	b.WriteString("\nConfidence (decision recorded in docs/iam/evaluator.md \"Edge confidence rule\"): `verified` = an Allow from complete documents that are all exact (collected, or the exact built-in AdministratorAccess) with no undecidable condition and a known resource-policy and SCP status, a typed inventory relationship no collected guardrail denies, or probe/simulator evidence; `inferred` = an Allow resting on unknown or approximate inputs (approximated managed policy, synthesised trust, default KMS key policy, incomplete principal, unknown SCPs, unknown cross-account caller) or any Unknown decision; `hint` = the statement heuristic fallback for documents the evaluator cannot parse, a scanner hint, or name/tag inference. Confidence is the only edge-level trust attribute.\n\n")
	b.WriteString("`validation` is reserved, not an edge key: `model.ValidationResult{status, probe_kind, evidence, at}` with status `theoretical` | `validated` | `refuted` | `unverifiable` (default `theoretical`) is the probe-status contract for paths and hops (plan v3 G3 / AP9), not yet attached.\n")
	return b.String()
}
