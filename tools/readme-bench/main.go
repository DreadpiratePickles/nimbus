// Command readme-bench rewrites the README benchmark block from lab/local/out/benchmark.json
// (written by `make groundtruth`), so the README never quotes stale numbers (delta review 2 #10).
//
//	go run ./tools/readme-bench [-json lab/local/out/benchmark.json] [-readme README.md] [-check]
//	go run ./tools/readme-bench -transcript [-bin ./bin/cloud-posture] [-check]   (transcript.go)
//
// It replaces everything between the BEGIN/END readme-bench markers. -check exits 1 when the
// block differs from what the JSON would generate.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"strings"
)

const (
	beginMarker = "<!-- BEGIN readme-bench"
	endMarker   = "<!-- END readme-bench -->"
	// Docs anchors the generated claims point at (tools/readme-claims resolves them).
	anchorNumbers = "docs/benchmark.md#honest-numbers-2026-10-09-labelled-and-real-world"
	anchorNoise   = "docs/benchmark.md#noise-estate-independently-authored"
	anchorGolden  = "docs/benchmark.md#scanner-interop-checkov--trivy-goldens"
)

type frac struct {
	Value *float64 `json:"value"`
	Num   int      `json:"num"`
	Den   int      `json:"den"`
}

func (f *frac) String() string {
	if f == nil || f.Den == 0 {
		return "—"
	}
	return fmt.Sprintf("%.1f%% (%d/%d)", 100*float64(f.Num)/float64(f.Den), f.Num, f.Den)
}

type view struct {
	Precision     frac  `json:"precision"`
	PrecisionHigh frac  `json:"precision_at_threshold"`
	Recall        frac  `json:"recall"`
	RecallHigh    frac  `json:"recall_at_threshold"`
	RecallBand    *frac `json:"recall_in_band"`
}

type findingLevel struct {
	CriticalOnNonExposed int `json:"critical_on_non_exposed"`
	BenignInTopN         int `json:"benign_in_top_n"`
	TopN                 int `json:"top_n"`
	RankedFindings       int `json:"ranked_findings"`
}

type estate struct {
	Threshold    float64           `json:"threshold"`
	Expected     int               `json:"expected_paths"`
	Reported     int               `json:"reported_paths"`
	ReportedHigh int               `json:"reported_paths_at_threshold"`
	Unlabelled   int               `json:"unlabelled_paths"`
	Labelled     view              `json:"labelled"`
	RealWorld    view              `json:"real_world"`
	RealFPs      []json.RawMessage `json:"real_world_false_positives"`
	FindingLevel *findingLevel     `json:"finding_level"`
}

type doc struct {
	Schema    string            `json:"schema"`
	Date      string            `json:"date"`
	Strict    bool              `json:"strict"`
	LiveCloud bool              `json:"live_cloud"`
	Estates   map[string]estate `json:"estates"`
}

// Render returns the block (markers included) for the benchmark document.
func Render(d doc) (string, error) {
	lab, ok := d.Estates["labelled_lab"]
	if !ok {
		return "", errors.New("benchmark.json has no labelled_lab estate (run `make groundtruth`)")
	}
	noise, hasNoise := d.Estates["noise_estate"]
	col := func(f func(e estate) string) string {
		n := "—"
		if hasNoise {
			n = f(noise)
		}
		return "| " + f(lab) + " | " + n + " |"
	}
	th := lab.Threshold
	if th == 0 {
		th = 7
	}
	live := "synthetic estates only (`live_cloud: false`)"
	if d.LiveCloud {
		live = "includes a live-cloud run (`live_cloud: true`)"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s: generated by `make readme-bench` from lab/local/out/benchmark.json; edit tools/readme-bench, not this block -->\n", beginMarker)
	fmt.Fprintf(&b, "Both estates are scored on every `make groundtruth`. The labelled lab is a seeded, deliberately vulnerable estate across seven accounts (AWS, Azure, GCP, EKS and GitHub) with %d expected attack paths plus false-positive and pending-feature labels; the noise estate was written by an independent author. Numbers from `benchmark.json`, measured **%s**, %s: <!-- claim: %s, tests/groundtruth/TestGroundTruth, tests/groundtruth/TestNoiseEstate -->\n\n",
		lab.Expected, d.Date, live, anchorNumbers)
	fmt.Fprintf(&b, "<!-- claim-table: %s tests/groundtruth/TestGroundTruth tests/groundtruth/TestNoiseEstate -->\n", anchorNumbers)
	b.WriteString("| metric | labelled lab (project-authored) | noise estate (independent author) |\n|---|---|---|\n")
	rows := []struct {
		name string
		f    func(e estate) string
	}{
		{"expected paths (labels)", func(e estate) string { return fmt.Sprint(e.Expected) }},
		{fmt.Sprintf("reported paths (all / score ≥ %.0f)", th), func(e estate) string { return fmt.Sprintf("%d / %d", e.Reported, e.ReportedHigh) }},
		{"precision, labelled", func(e estate) string { return e.Labelled.Precision.String() }},
		{"precision, real-world", func(e estate) string { return e.RealWorld.Precision.String() }},
		{fmt.Sprintf("precision@%.0f, real-world", th), func(e estate) string { return e.RealWorld.PrecisionHigh.String() }},
		{"recall (any score), real-world", func(e estate) string { return e.RealWorld.Recall.String() }},
		{fmt.Sprintf("recall@%.0f, labelled / real-world", th), func(e estate) string {
			return e.Labelled.RecallHigh.String() + " / " + e.RealWorld.RecallHigh.String()
		}},
		{"recall in band, real-world", func(e estate) string { return e.RealWorld.RecallBand.String() }},
		{"unlabelled paths", func(e estate) string { return fmt.Sprint(e.Unlabelled) }},
		{"real-world false positives", func(e estate) string { return fmt.Sprint(len(e.RealFPs)) }},
	}
	for _, r := range rows {
		fmt.Fprintf(&b, "| %s %s\n", r.name, col(r.f))
	}
	if fl := lab.FindingLevel; fl != nil {
		fmt.Fprintf(&b, "| finding level: Critical findings on a blocked, false-positive or pending-feature resource (target 0) | %d of %d ranked | — |\n", fl.CriticalOnNonExposed, fl.RankedFindings)
		fmt.Fprintf(&b, "| finding level: such resources in the `prioritize` top %d (target 0) | %d | — |\n", fl.TopN, fl.BenignInTopN)
	}
	b.WriteString("\n**Read these numbers with care.** The labelled lab and its labels were written by the project that tuned the engine. The noise estate was written independently, but the engine's noise round was tuned on its false positives, so its precision is in-sample, not held-out. Checkov and Trivy golden outputs of the lab Terraform are scored separately (`make groundtruth-golden`). No live cloud has been scanned yet. This is a regression benchmark, not a comparison with other tools. ")
	fmt.Fprintf(&b, "<!-- claim: %s, %s, tests/groundtruth/TestGoldenScannerInterop -->\n", anchorNoise, anchorGolden)
	b.WriteString(endMarker)
	return b.String(), nil
}

// Rewrite replaces the marked block of readme with block.
func Rewrite(readme []byte, block string) ([]byte, error) {
	i := bytes.Index(readme, []byte(beginMarker))
	j := bytes.Index(readme, []byte(endMarker))
	if i < 0 || j < i {
		return nil, fmt.Errorf("README has no %q … %q block", beginMarker, endMarker)
	}
	var out bytes.Buffer
	out.Write(readme[:i])
	out.WriteString(block)
	out.Write(readme[j+len(endMarker):])
	return out.Bytes(), nil
}

func main() {
	jsonPath := flag.String("json", "lab/local/out/benchmark.json", "benchmark.json written by make groundtruth")
	readmePath := flag.String("readme", "README.md", "README to rewrite")
	check := flag.Bool("check", false, "exit 1 when the README block is stale instead of rewriting it")
	tr := flag.Bool("transcript", false, "rewrite (or -check) the quickstart transcript block from the real binary on the lab instead of the benchmark block")
	bin := flag.String("bin", "", "with -transcript: the cloud-posture binary to run (default: go build ./cmd/cloud-posture)")
	flag.Parse()
	if *tr {
		if err := transcript(*bin, *readmePath, *check); err != nil {
			fmt.Fprintln(os.Stderr, "readme-bench:", err)
			os.Exit(1)
		}
		return
	}
	if err := run(*jsonPath, *readmePath, *check); err != nil {
		fmt.Fprintln(os.Stderr, "readme-bench:", err)
		os.Exit(1)
	}
}

func run(jsonPath, readmePath string, check bool) error {
	raw, err := os.ReadFile(jsonPath)
	if err != nil {
		return fmt.Errorf("%w (run `make groundtruth` first)", err)
	}
	var d doc
	if err := json.Unmarshal(raw, &d); err != nil {
		return fmt.Errorf("%s: %w", jsonPath, err)
	}
	if d.Schema != "nimbus.benchmark/v1" {
		return fmt.Errorf("%s: schema %q, want nimbus.benchmark/v1", jsonPath, d.Schema)
	}
	block, err := Render(d)
	if err != nil {
		return err
	}
	readme, err := os.ReadFile(readmePath)
	if err != nil {
		return err
	}
	out, err := Rewrite(readme, block)
	if err != nil {
		return err
	}
	if check {
		if !bytes.Equal(out, readme) {
			return fmt.Errorf("%s benchmark block is stale against %s; run `make readme-bench`", readmePath, jsonPath)
		}
		fmt.Println("readme-bench: README benchmark block is current")
		return nil
	}
	if bytes.Equal(out, readme) {
		fmt.Println("readme-bench: README benchmark block already current")
		return nil
	}
	if err := os.WriteFile(readmePath, out, 0o644); err != nil {
		return err
	}
	fmt.Printf("readme-bench: rewrote the benchmark block of %s from %s\n", readmePath, jsonPath)
	return nil
}
