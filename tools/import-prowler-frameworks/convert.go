const (
	license     = "Apache-2.0"
	attribution = "Requirement-to-check mappings from Prowler (https://github.com/prowler-cloud/prowler), Apache-2.0, Copyright 2024 Toni de la Fuente. Converted by nimbus tools/import-prowler-frameworks; check ids translated to nimbus canonical ids."
	cisBenchURL = "https://www.cisecurity.org/cis-benchmarks"
	cisCtrlURL  = "https://www.cisecurity.org/controls"
	header      = "# Generated by tools/import-prowler-frameworks from Prowler's compliance JSON. Do not edit by hand.\n# Ids and mappings only; see THIRD_PARTY_NOTICES.md section 2 for the text policy.\n"
	maxTitle    = 160
)

type options struct {
	Ref, SHA              string
	CISText, UpstreamText bool
	// Lookup returns the canonical id for a Prowler check, its catalog title and whether nimbus
	// knows it natively (catalog entry) rather than only as "PROWLER:<check>".
	Lookup func(check string) (canonical, title string, native bool)
}

func (o options) source() string { return fmt.Sprintf("prowler@%s (%s)", o.Ref, o.SHA) }

type outRequirement struct {
	ID            string   `yaml:"id"`
	Title         string   `yaml:"title"`
	Section       string   `yaml:"section,omitempty"`
	Checks        []string `yaml:"checks,flow,omitempty"`
	ProwlerChecks []string `yaml:"prowler_checks,flow,omitempty"`
}

type outFile struct {
	Key          string           `yaml:"key"`
	Name         string           `yaml:"name"`
	Version      string           `yaml:"version"`
	Provider     string           `yaml:"provider"`
	Framework    string           `yaml:"framework"`
	Source       string           `yaml:"source"`
	UpstreamPath string           `yaml:"upstream_path"`
	UpstreamURL  string           `yaml:"upstream_url"`
	License      string           `yaml:"license"`
	Attribution  string           `yaml:"attribution"`
	TextPolicy   string           `yaml:"text_policy"`
	ReferenceURL string           `yaml:"reference_url,omitempty"`
	Requirements []outRequirement `yaml:"requirements"`
}

type indexEntry struct {
	Key          string `yaml:"key"`
	UpstreamPath string `yaml:"upstream_path"`
	Requirements int    `yaml:"requirements"`
	SHA256       string `yaml:"sha256"`
}

type index struct {
	Source       string       `yaml:"source"`
	Repository   string       `yaml:"repository"`
	License      string       `yaml:"license"`
	Attribution  string       `yaml:"attribution"`
	CISText      bool         `yaml:"cis_text"`
	UpstreamText bool         `yaml:"upstream_text"`
	Files        []indexEntry `yaml:"files"`
}

// upstream mirrors both Prowler shapes: per-provider files (capitalised keys, list attributes,
// list checks) and universal top-level files (lower-case keys, map attributes, checks by provider).
type upstreamReq struct {
	Id          json.RawMessage `json:"Id"`
	Name        string          `json:"Name"`
	Description string          `json:"Description"`
	Attributes  json.RawMessage `json:"Attributes"`
	Checks      json.RawMessage `json:"Checks"`
}

type upstreamFile struct {
	Framework    string          `json:"Framework"`
	Name         string          `json:"Name"`
	Version      json.RawMessage `json:"Version"`
	Provider     string          `json:"Provider"`
	Requirements json.RawMessage `json:"Requirements"`
}

// isCIS reports whether a file reproduces Center for Internet Security content (Benchmarks or the
// CIS Controls). CISA (a U.S. agency) is not CIS.
func isCIS(framework, key string) bool {
	return framework == "CIS" || strings.HasPrefix(framework, "CIS-") || strings.HasPrefix(key, "cis_")
}

func convert(rel string, data []byte, opt options) (*outFile, error) {
	key := strings.TrimSuffix(path.Base(rel), ".json")
	// encoding/json matches field names case-insensitively, so one struct decodes both shapes.
	var up upstreamFile
	if err := json.Unmarshal(data, &up); err != nil {
		return nil, fmt.Errorf("%s: %w", rel, err)
	}
	if len(up.Requirements) == 0 || string(up.Requirements) == "null" {
		return nil, fmt.Errorf("%s: no Requirements/requirements array; refusing to import", rel)
	}
	var reqs []upstreamReq
	if err := json.Unmarshal(up.Requirements, &reqs); err != nil {
		return nil, fmt.Errorf("%s: requirements: %w", rel, err)
	}
	cis := isCIS(up.Framework, key)
	copyText := (cis && opt.CISText) || (!cis && opt.UpstreamText)
	upstreamPath := "prowler/compliance/" + rel
	out := &outFile{
		Key: key, Name: clean(up.Name), Version: scalar(up.Version), Framework: up.Framework,
		Source: opt.source(), UpstreamPath: upstreamPath, UpstreamURL: repoURL + "/blob/" + opt.SHA + "/" + upstreamPath,
		License: license, Attribution: attribution,
	}
	if cis {
		out.ReferenceURL = cisBenchURL
		if strings.HasPrefix(key, "cis_controls") || up.Framework == "CIS-Controls" {
			out.ReferenceURL = cisCtrlURL
		}
	}
	providers := map[string]bool{}
	if dir := path.Dir(rel); dir != "." {
		providers[dir] = true
	}
	anyTitle := false
	for i, r := range reqs {
		id := scalar(r.Id)
		if id == "" {
			return nil, fmt.Errorf("%s: requirement #%d has no id", rel, i+1)
		}
		raw, err := parseChecks(r.Checks, providers)
		if err != nil {
			return nil, fmt.Errorf("%s: requirement %s: %w", rel, id, err)
		}
		req := outRequirement{ID: id, ProwlerChecks: raw}
		canon := map[string]bool{}
		titles := map[string]string{}
		for _, c := range raw {
			cid, title, native := opt.Lookup(c)
			canon[cid] = true
			if native {
				titles[cid] = title
			}
		}
		req.Checks = sortedKeys(canon)
		for _, cid := range req.Checks {
			if t, ok := titles[cid]; ok {
				req.Title = t
				break
			}
		}
		if copyText {
			if t := clean(r.Name); t != "" {
				req.Title = truncate(t)
			} else if t := clean(r.Description); t != "" {
				req.Title = truncate(t)
			}
			req.Section = truncate(section(r.Attributes))
		}
		if req.Title != "" {
			anyTitle = true
		}
		out.Requirements = append(out.Requirements, req)
	}
	switch {
	case copyText:
		out.TextPolicy = "upstream"
	case anyTitle:
		out.TextPolicy = "nimbus-titles"
	default:
		out.TextPolicy = "ids-only"
	}
	out.Provider = strings.Join(sortedKeys(providers), ",")
	return out, nil
}

// parseChecks accepts a list of check ids or a provider -> list map (universal files).
func parseChecks(raw json.RawMessage, providers map[string]bool) ([]string, error) {
	set := map[string]bool{}
	if len(raw) != 0 && string(raw) != "null" {
		var list []string
		if err := json.Unmarshal(raw, &list); err != nil {
			var byProvider map[string][]string
			if err2 := json.Unmarshal(raw, &byProvider); err2 != nil {
				return nil, fmt.Errorf("checks: %w", err)
			}
			for p, l := range byProvider {
				if len(l) > 0 {
					providers[strings.ToLower(p)] = true
				}
				list = append(list, l...)
			}
		}
		for _, c := range list {
			if c = strings.TrimSpace(c); c != "" {
				set[c] = true
			}
		}
	}
	return sortedKeys(set), nil
}

func section(raw json.RawMessage) string {
	var list []map[string]any
	if json.Unmarshal(raw, &list) == nil {
		for _, a := range list {
			if s, ok := a["Section"].(string); ok && s != "" {
				return clean(s)
			}
		}
		return ""
	}
	var m map[string]any
	if json.Unmarshal(raw, &m) == nil {
		if s, ok := m["Section"].(string); ok {
			return clean(s)
		}
	}
	return ""
}

// scalar renders a JSON string or number verbatim.
func scalar(raw json.RawMessage) string {
	if len(raw) == 0 || string(raw) == "null" {
		return ""
	}
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return strings.TrimSpace(s)
	}
	return strings.TrimSpace(string(raw))
}

func clean(s string) string { return strings.Join(strings.Fields(s), " ") }

func truncate(s string) string {
	r := []rune(s)
	if len(r) <= maxTitle {
		return s
	}
	return strings.TrimSpace(string(r[:maxTitle-3])) + "..."
}

func marshal(v any) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// writeAll converts every file, then writes <key>.yaml and index.yaml into outDir. Nothing is
// written unless every file converts. Files listed in a previous index but no longer produced are
// removed, so re-running against the same tree is a no-op.
func writeAll(outDir string, files map[string][]byte, opt options) (*index, error) {
	idx := &index{Source: opt.source(), Repository: repoURL, License: license, Attribution: attribution, CISText: opt.CISText, UpstreamText: opt.UpstreamText}
	outputs := map[string][]byte{}
	for _, rel := range sortedKeys(files) {
		f, err := convert(rel, files[rel], opt)
		if err != nil {
			return nil, err
		}
		if _, dup := outputs[f.Key]; dup {
			return nil, fmt.Errorf("%s: key %q is produced by two upstream files", rel, f.Key)
		}
		data, err := marshal(f)
		if err != nil {
			return nil, err
		}
		outputs[f.Key] = data
		sum := sha256.Sum256(files[rel])
		idx.Files = append(idx.Files, indexEntry{Key: f.Key, UpstreamPath: f.UpstreamPath, Requirements: len(f.Requirements), SHA256: hex.EncodeToString(sum[:])})
	}
	sort.Slice(idx.Files, func(i, j int) bool { return idx.Files[i].Key < idx.Files[j].Key })
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return nil, err
	}
	if old, err := os.ReadFile(filepath.Join(outDir, "index.yaml")); err == nil {
		var prev index
		if yaml.Unmarshal(old, &prev) == nil {
			for _, e := range prev.Files {
				if _, keep := outputs[e.Key]; !keep && e.Key != "" && !strings.ContainsAny(e.Key, `/\`) {
					os.Remove(filepath.Join(outDir, e.Key+".yaml"))
				}
			}
		}
	}
	for _, k := range sortedKeys(outputs) {
		if err := os.WriteFile(filepath.Join(outDir, k+".yaml"), outputs[k], 0o644); err != nil {
			return nil, err
		}
	}
	data, err := marshal(idx)
	if err != nil {
		return nil, err
	}
	return idx, os.WriteFile(filepath.Join(outDir, "index.yaml"), data, 0o644)
}
